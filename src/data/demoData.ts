export function createInitialDemoWorkspace(): TerraWorkspaceState {
  const settings = {
    ...DEFAULT_SYSTEM_SETTINGS,
    demoModeEnabled: true,
    municipalityName: 'Metro Public Works Authority (Demo Sandbox)',
    coordinateReferenceLabel: 'Simulated Municipal Grid (WGS84 / OSM)',
    firebaseStatus: 'DEMO MODE (Simulated Sandbox — Live Firestore Isolated)',
  };

  // Build pothole records first with initial priority scores
  let potholes: PotholeRecord[] = RAW_POTHOLE_SEEDS.map((seed) => {
    const detectedAt = hoursAgo(seed.detectedHoursAgo);
    const initialPriority = calculatePotholePriority(
      {
        severity: seed.severity,
        peakAccelG: seed.peakAccelG,
        arterialClass: seed.arterialClass,
        clusterNeighborCount: 2,
        detectedAt,
      },
      settings.priorityWeights
    );

    return {
      id: seed.id,
      roadName: seed.roadName,
      segmentCode: seed.segmentCode,
      district: seed.district,
      arterialClass: seed.arterialClass,
      lat: seed.lat,
      lng: seed.lng,
      h3Index: '',
      clusterId: null,
      classification: 'Pothole',
      severity: seed.severity,
      status: seed.status,
      priorityScore: initialPriority.totalScore,
      priorityTier: initialPriority.tier,
      detectedAt,
      updatedAt: detectedAt,
      deviceId: seed.deviceId,
      telemetry: {
        peakAccelG: seed.peakAccelG,
        rmsVibration: seed.rmsVibration,
        iriScore: seed.iriScore,
        durationMs: Math.round(90 + seed.peakAccelG * 22),
        speedKmh: seed.speedKmh,
        mlConfidence: seed.mlConfidence,
        waveformSample: buildPulseWaveform(seed.peakAccelG),
      },
      detectionCount: seed.detectionCount,
      assignedWorkOrderId: seed.assignedWorkOrderId,
      notes: seed.notes,
      dataSource: 'SIMULATED_DEMO',
    };
  });

  // Compute real DBSCAN clusters and H3 hex cells
  const { clusters, pointClusterMap } = runDbscanClustering(
    potholes,
    settings.dbscanDefaultEpsMeters,
    settings.dbscanDefaultMinPts
  );
  const h3Cells = generateH3HexGrid(potholes, settings.h3DefaultResolution);

  const h3Lookup = new Map<string, string>();
  for (const cell of h3Cells) {
    for (const pid of cell.potholeIds) {
      h3Lookup.set(pid, cell.h3Index);
    }
  }

  // Enrich potholes with cluster IDs, H3 indices, and density-aware priority scores
  potholes = potholes.map((p) => {
    const clusterId = pointClusterMap.get(p.id) || null;
    const clusterSize = clusterId
      ? clusters.find((c) => c.id === clusterId)?.potholeCount || 1
      : 1;
    const priority = calculatePotholePriority(
      {
        severity: p.severity,
        peakAccelG: p.telemetry.peakAccelG,
        arterialClass: p.arterialClass,
        clusterNeighborCount: clusterSize,
        detectedAt: p.detectedAt,
      },
      settings.priorityWeights
    );
    return {
      ...p,
      verified: p.status === 'Detected' ? false : true,
      hasReliableGps: true,
      clusterId,
      h3Index: h3Lookup.get(p.id) || '8928308280fffff',
      priorityScore: priority.totalScore,
      priorityTier: priority.tier,
    };
  });

  return {
    potholes,
    clusters,
    h3Cells,
    zones: INITIAL_ZONES,
    repairs: INITIAL_REPAIRS,
    repairHistory: INITIAL_REPAIR_HISTORY,
    crews: INITIAL_CREWS,
    alerts: INITIAL_ALERTS,
    devices: INITIAL_DEVICES,
    users: INITIAL_USERS,
    settings,
  };
}
