function buildPulseWaveform(peakG: number): number[] {
  return [
    0.98, 1.02, 0.99, 1.05, 0.96, 1.18,
    Number((peakG * 0.65).toFixed(2)),
    Number(peakG.toFixed(2)),
    Number((-peakG * 0.42).toFixed(2)),
    Number((peakG * 0.35).toFixed(2)),
    1.15, 0.92, 1.06, 0.99, 1.01, 1.0,
  ];
}

function buildDeviceAccelStream(baseNoise: number) {
  return Array.from({ length: 12 }, (_, i) => ({
    t: `T-${(12 - i) * 2}s`,
    ax: Number((((i % 3) - 1) * 0.08 * baseNoise).toFixed(2)),
    ay: Number((((i % 4) - 1.5) * 0.06 * baseNoise).toFixed(2)),
    az: Number((1.0 + (i === 7 ? baseNoise * 1.4 : ((i % 2 === 0 ? 1 : -1) * 0.09 * baseNoise))).toFixed(2)),
  }));
}

